/**
 * Generates an external, MV3 CSP-safe Safari runtime compatibility shim that
 * fills specific API gaps observed when running Chrome MV3 extensions inside
 * Safari / WKWebExtension without faking top-level feature-detected Chrome APIs
 * (such as `chrome.offscreen` or `chrome.sidePanel`):
 *
 * 1. `scripting.ExecutionWorld` enum (`ISOLATED` / `MAIN`) — missing in Safari
 *    even though `scripting.registerContentScripts` / `executeScript` accept
 *    those strings (fixes React Developer Tools et al.).
 * 2. Missing `webNavigation` events (`onHistoryStateUpdated`, `onTabReplaced`)
 *    stubbed as spec-shaped Event objects (fixes Vimium et al.).
 * 3. `webRequest.<event>.addListener` strips unsupported non-HTTP schemes
 *    (e.g. `ws://`, `wss://`, `ftp://`) from `filter.urls` instead of throwing
 *    synchronously (fixes Privacy Badger et al.).
 * 4. `permissions.contains` / `request` / `remove` gracefully return `false`
 *    when queried with a Chrome-only permission name Safari does not recognize
 *    (e.g. `webRequestBlocking`) instead of rejecting (fixes Stylus et al.).
 * 5. `notifications` event listeners (`onClicked`, `onClosed`, `onButtonClicked`,
 *    `onShown`) tolerate Safari's "not supported" throw on `addListener`
 *    (fixes Bitwarden et al.).
 */
export function buildSafariRuntimeShim(): string {
  return `/* Generated by extport for Safari Web Extension runtime compatibility. */
(() => {
  const g = globalThis;
  if (g.__EXTPORT_SAFARI_SHIM__) return;
  g.__EXTPORT_SAFARI_SHIM__ = true;

  const createNoopEvent = () => {
    const listeners = new Set();
    return {
      addListener(fn) {
        if (typeof fn === 'function') listeners.add(fn);
      },
      removeListener(fn) {
        listeners.delete(fn);
      },
      hasListener(fn) {
        return listeners.has(fn);
      },
      hasListeners() {
        return listeners.size > 0;
      },
    };
  };

  const VALID_SAFARI_URL_PATTERN_RE = /^(?:<all_urls>|(?:https?|file|\\*):\\/\\/)/i;
  const INVALID_PERM_RE = /not a valid permission|invalid permission|unknown permission/i;
  const NOT_SUPPORTED_RE = /not supported/i;

  const patchNamespace = (api) => {
    if (!api || typeof api !== 'object') return;

    // 1. chrome.scripting.ExecutionWorld enum
    try {
      if (api.scripting && !api.scripting.ExecutionWorld) {
        api.scripting.ExecutionWorld = Object.freeze({
          ISOLATED: 'ISOLATED',
          MAIN: 'MAIN',
        });
      }
    } catch {}

    // 2. Missing chrome.webNavigation events
    try {
      if (api.webNavigation) {
        for (const ev of [
          'onBeforeNavigate',
          'onCommitted',
          'onDOMContentLoaded',
          'onCompleted',
          'onErrorOccurred',
          'onCreatedNavigationTarget',
          'onReferenceFragmentUpdated',
          'onHistoryStateUpdated',
          'onTabReplaced',
        ]) {
          if (!api.webNavigation[ev]) {
            api.webNavigation[ev] = createNoopEvent();
          }
        }
      }
    } catch {}

    // 3. chrome.webRequest: option enums + addListener URL scheme sanitization
    try {
      if (api.webRequest) {
        const optionEnums = {
          OnBeforeRequestOptions: { REQUEST_BODY: 'requestBody' },
          OnBeforeSendHeadersOptions: { REQUEST_HEADERS: 'requestHeaders' },
          OnSendHeadersOptions: { REQUEST_HEADERS: 'requestHeaders' },
          OnHeadersReceivedOptions: { RESPONSE_HEADERS: 'responseHeaders' },
          OnAuthRequiredOptions: { RESPONSE_HEADERS: 'responseHeaders' },
          OnResponseStartedOptions: { RESPONSE_HEADERS: 'responseHeaders' },
          OnBeforeRedirectOptions: { RESPONSE_HEADERS: 'responseHeaders' },
          OnCompletedOptions: { RESPONSE_HEADERS: 'responseHeaders' },
        };
        for (const [k, v] of Object.entries(optionEnums)) {
          if (!api.webRequest[k]) {
            api.webRequest[k] = Object.freeze(v);
          }
        }
        const events = [
          'onBeforeRequest',
          'onBeforeSendHeaders',
          'onSendHeaders',
          'onHeadersReceived',
          'onAuthRequired',
          'onResponseStarted',
          'onBeforeRedirect',
          'onCompleted',
          'onErrorOccurred',
        ];
        for (const name of events) {
          const ev = api.webRequest[name];
          if (!ev || typeof ev.addListener !== 'function' || ev.__extportWrapped) continue;
          const origAdd = ev.addListener.bind(ev);
          ev.addListener = function (callback, filter, ...rest) {
            let nextFilter = filter;
            if (filter && typeof filter === 'object' && Array.isArray(filter.urls)) {
              const validUrls = filter.urls.filter(
                (u) => typeof u === 'string' && VALID_SAFARI_URL_PATTERN_RE.test(u.trim()),
              );
              if (validUrls.length === 0 && filter.urls.length > 0) {
                return;
              }
              if (validUrls.length !== filter.urls.length) {
                nextFilter = Object.assign({}, filter, { urls: validUrls });
              }
            }
            try {
              return origAdd(callback, nextFilter, ...rest);
            } catch (err) {
              if (Array.isArray(rest[0])) {
                const cleanedSpec = rest[0].filter((s) => s !== 'extraHeaders' && s !== 'blocking');
                if (cleanedSpec.length !== rest[0].length) {
                  try {
                    return cleanedSpec.length > 0
                      ? origAdd(callback, nextFilter, cleanedSpec, ...rest.slice(1))
                      : origAdd(callback, nextFilter, ...rest.slice(1));
                  } catch {}
                }
              }
              throw err;
            }
          };
          ev.__extportWrapped = true;
        }
      }
    } catch {}

    // 4. chrome.permissions.contains / request / remove: return false on Safari-unknown permission names
    try {
      if (api.permissions) {
        for (const method of ['contains', 'request', 'remove']) {
          const orig = api.permissions[method];
          if (typeof orig !== 'function' || orig.__extportWrapped) continue;
          const bound = orig.bind(api.permissions);
          const wrapped = function (details, callback) {
            if (typeof callback === 'function') {
              try {
                return bound(details, callback);
              } catch (err) {
                if (INVALID_PERM_RE.test(String(err))) {
                  queueMicrotask(() => callback(false));
                  return;
                }
                throw err;
              }
            }
            try {
              const res = bound(details);
              if (res && typeof res.then === 'function') {
                return res.catch((err) => {
                  if (INVALID_PERM_RE.test(String(err))) return false;
                  throw err;
                });
              }
              return res;
            } catch (err) {
              if (INVALID_PERM_RE.test(String(err))) return Promise.resolve(false);
              throw err;
            }
          };
          wrapped.__extportWrapped = true;
          api.permissions[method] = wrapped;
        }
      }
    } catch {}

    // 5. chrome.action.setBadgeTextColor / getBadgeTextColor (Chrome 110+, missing in Safari)
    try {
      if (api.action) {
        if (typeof api.action.setBadgeTextColor !== 'function') {
          api.action.setBadgeTextColor = function (_details, callback) {
            if (typeof callback === 'function') {
              queueMicrotask(() => callback());
              return;
            }
            return Promise.resolve();
          };
        }
        if (typeof api.action.getBadgeTextColor !== 'function') {
          api.action.getBadgeTextColor = function (_details, callback) {
            const color = [255, 255, 255, 255];
            if (typeof callback === 'function') {
              queueMicrotask(() => callback(color));
              return;
            }
            return Promise.resolve(color);
          };
        }
      }
    } catch {}

    // 6. chrome.idle (only when declared in manifest.permissions and absent in Safari)
    try {
      if (!api.idle && api.runtime && typeof api.runtime.getManifest === 'function') {
        const m = api.runtime.getManifest();
        const perms = Array.isArray(m && m.permissions) ? m.permissions : [];
        if (perms.includes('idle')) {
          api.idle = {
            queryState(_intervalInSeconds, callback) {
              if (typeof callback === 'function') {
                queueMicrotask(() => callback('active'));
                return;
              }
              return Promise.resolve('active');
            },
            setDetectionInterval() {},
            getAutoLockDelay(callback) {
              if (typeof callback === 'function') {
                queueMicrotask(() => callback(0));
                return;
              }
              return Promise.resolve(0);
            },
            onStateChanged: createNoopEvent(),
          };
        }
      }
    } catch {}

    // 7. chrome.notifications missing / throwing event listeners
    try {
      if (api.notifications) {
        for (const name of ['onClicked', 'onClosed', 'onButtonClicked', 'onShown']) {
          const ev = api.notifications[name];
          if (!ev) {
            api.notifications[name] = createNoopEvent();
            continue;
          }
          if (typeof ev.addListener === 'function' && !ev.__extportWrapped) {
            const origAdd = ev.addListener.bind(ev);
            ev.addListener = function (...args) {
              try {
                return origAdd(...args);
              } catch (err) {
                if (NOT_SUPPORTED_RE.test(String(err))) return;
                throw err;
              }
            };
            ev.__extportWrapped = true;
          }
        }
      }
    } catch {}
  };

  const seen = new Set();
  for (const ns of [g.chrome, g.browser]) {
    if (ns && !seen.has(ns)) {
      seen.add(ns);
      patchNamespace(ns);
    }
  }
})();
`
}

/**
 * Cleans up Chrome-only manifest entries that cause Safari / WKWebExtension
 * load errors or converter warnings, returning a list of human-readable change
 * labels when the manifest was modified.
 */
export function normalizeManifestForSafari(manifest: Record<string, unknown>): string[] {
  const changes: string[] = []

  // Safari rejects empty command objects like `"_execute_action": {}` with
  // WKWebExtensionErrorDomain code 6 ("Empty or invalid command").
  if (manifest.commands && typeof manifest.commands === 'object' && !Array.isArray(manifest.commands)) {
    const commands = manifest.commands as Record<string, unknown>
    let removedAny = false
    for (const [key, val] of Object.entries(commands)) {
      if (!val || typeof val !== 'object' || Array.isArray(val)) {
        delete commands[key]
        removedAny = true
        continue
      }
      const entry = val as Record<string, unknown>
      const hasDesc = typeof entry.description === 'string' && entry.description.trim().length > 0
      const hasKey =
        entry.suggested_key !== undefined &&
        entry.suggested_key !== null &&
        typeof entry.suggested_key === 'object' &&
        Object.keys(entry.suggested_key as Record<string, unknown>).length > 0
      if (!hasDesc && !hasKey) {
        delete commands[key]
        removedAny = true
      }
    }
    if (removedAny) {
      if (Object.keys(commands).length === 0) delete manifest.commands
      changes.push('stripped empty commands')
    }
  }

  // Safari only supports "spanning" or "not_allowed" for incognito, never "split".
  if (manifest.incognito === 'split') {
    delete manifest.incognito
    changes.push('removed incognito=split')
  }

  // Safari does not support web_accessible_resources[].use_dynamic_url.
  if (Array.isArray(manifest.web_accessible_resources)) {
    let strippedDynamicUrl = false
    for (const item of manifest.web_accessible_resources) {
      if (item && typeof item === 'object' && 'use_dynamic_url' in item) {
        delete (item as Record<string, unknown>).use_dynamic_url
        strippedDynamicUrl = true
      }
    }
    if (strippedDynamicUrl) changes.push('stripped use_dynamic_url')
  }

  // Chrome-only managed enterprise storage schema (unused & warned in Safari).
  if (
    manifest.storage &&
    typeof manifest.storage === 'object' &&
    !Array.isArray(manifest.storage) &&
    'managed_schema' in manifest.storage
  ) {
    const storageObj = manifest.storage as Record<string, unknown>
    delete storageObj.managed_schema
    if (Object.keys(storageObj).length === 0) delete manifest.storage
    changes.push('stripped storage.managed_schema')
  }

  // Chrome-store / editor metadata unsupported by Safari.
  let strippedNoise = false
  for (const noiseKey of ['update_url', 'minimum_chrome_version', '$schema', 'offline_enabled'] as const) {
    if (noiseKey in manifest) {
      delete manifest[noiseKey]
      strippedNoise = true
    }
  }
  if (strippedNoise) changes.push('stripped Chrome-only metadata')

  return changes
}

/**
 * Injects missing `<meta name="viewport">` and `<meta name="color-scheme" content="light dark">`
 * early in `<head>` (to avoid FOUC), an optional external runtime shim `<script>`
 * right after the metas, and an optional `<link rel="stylesheet">` right before `</head>`.
 * Idempotent and preserves any explicit viewport or color-scheme already declared by the extension.
 */
export function patchHtmlDocument(
  html: string,
  stylesheetHref: string | undefined,
  runtimeScriptHref?: string,
): string {
  const earlyTags: string[] = []
  if (stylesheetHref !== undefined) {
    if (!HAS_VIEWPORT_RE.test(html)) earlyTags.push(VIEWPORT_META)
    if (!HAS_COLOR_SCHEME_RE.test(html)) earlyTags.push(COLOR_SCHEME_META)
  }
  const hasRuntimeScript = !runtimeScriptHref || html.includes(COMPAT_RUNTIME_SCRIPT_NAME)
  if (!hasRuntimeScript && runtimeScriptHref) {
    earlyTags.push(`<script src="${runtimeScriptHref}"></script>`)
  }

  const linkTag = stylesheetHref ? `<link rel="stylesheet" href="${stylesheetHref}" />` : undefined
  const hasStylesheet = !linkTag || html.includes(COMPAT_STYLESHEET_NAME)

  if (earlyTags.length === 0 && hasStylesheet) {
    return html
  }

  const headOpenMatch = HEAD_OPEN_RE.exec(html)
  const headCloseMatch = HEAD_CLOSE_RE.exec(html)
  if (headOpenMatch && headCloseMatch && headCloseMatch.index > headOpenMatch.index) {
    let result = html
    if (earlyTags.length > 0) {
      const insertPos = headOpenMatch.index + headOpenMatch[0].length
      const earlyBlock = `\n    ${earlyTags.join('\n    ')}`
      result = `${result.slice(0, insertPos)}${earlyBlock}${result.slice(insertPos)}`
    }
    if (!hasStylesheet && linkTag) {
      const updatedCloseMatch = HEAD_CLOSE_RE.exec(result)
      if (updatedCloseMatch) {
        result = `${result.slice(0, updatedCloseMatch.index)}    ${linkTag}\n  ${result.slice(updatedCloseMatch.index)}`
      }
    }
    return result
  }

  const headLines = [...earlyTags, ...(!hasStylesheet && linkTag ? [linkTag] : [])]
  const headBlock = `<head>\n    ${headLines.join('\n    ')}\n  </head>`

  const htmlOpenMatch = HTML_OPEN_RE.exec(html)
  if (htmlOpenMatch) {
    const insertPos = htmlOpenMatch.index + htmlOpenMatch[0].length
    return `${html.slice(0, insertPos)}\n  ${headBlock}${html.slice(insertPos)}`
  }

  const doctypeMatch = DOCTYPE_RE.exec(html)
  if (doctypeMatch) {
    const insertPos = doctypeMatch.index + doctypeMatch[0].length
    return `${html.slice(0, insertPos)}\n${headBlock}\n${html.slice(insertPos)}`
  }

  return `${headBlock}\n${html}`
}

async function isRegularFile(filePath: string): Promise<boolean> {
  try {
    return (await stat(filePath)).isFile()
  } catch {
    return false
  }
}

function toRelativePosixHref(fromFilePosix: string, targetPosix: string): string {
  const rel = path.posix.relative(path.posix.dirname(fromFilePosix), targetPosix)
  return rel.startsWith('.') ? rel : `./${rel}`
}

async function wireBackgroundRuntimeShim(root: string, manifest: Record<string, unknown>): Promise<boolean> {
  const bg = manifest.background
  if (!bg || typeof bg !== 'object' || Array.isArray(bg)) return false
  const background = bg as Record<string, unknown>
  let changed = false

  const isModule = background.type === 'module'

  // Wrap service_worker in-directory so relative importScripts() / fetch() stay intact.
  if (typeof background.service_worker === 'string') {
    const swNormalized = normalizeManifestPagePath(background.service_worker)
    if (swNormalized && path.posix.basename(swNormalized) !== COMPAT_BG_WRAPPER_NAME) {
      const swFull = path.resolve(root, swNormalized)
      const rel = path.relative(root, swFull)
      if (rel && !rel.startsWith('..') && !path.isAbsolute(rel) && (await isRegularFile(swFull))) {
        const swPosix = rel.split(path.sep).join('/')
        const swDirPosix = path.posix.dirname(swPosix)
        const swBase = path.posix.basename(swPosix)
        const wrapperPosix =
          swDirPosix === '.' ? COMPAT_BG_WRAPPER_NAME : path.posix.join(swDirPosix, COMPAT_BG_WRAPPER_NAME)
        const runtimeHref = toRelativePosixHref(wrapperPosix, COMPAT_RUNTIME_SCRIPT_NAME)
        const targetHref = `./${swBase}`
        const wrapperCode = isModule
          ? `import ${JSON.stringify(runtimeHref)};\nimport ${JSON.stringify(targetHref)};\n`
          : `importScripts(${JSON.stringify(runtimeHref)}, ${JSON.stringify(targetHref)});\n`
        await writeFile(path.join(root, ...wrapperPosix.split('/')), wrapperCode, 'utf-8')
        const hadLeadingSlash = background.service_worker.trim().startsWith('/')
        background.service_worker = hadLeadingSlash ? `/${wrapperPosix}` : wrapperPosix
        changed = true
      }
    }
  }

  // Also prepend the runtime shim to background.scripts when present (Safari prefers
  // `scripts` over `service_worker` if an extension declares both).
  if (Array.isArray(background.scripts)) {
    const alreadyPresent = background.scripts.some(
      (s) => typeof s === 'string' && normalizeManifestPagePath(s) === COMPAT_RUNTIME_SCRIPT_NAME,
    )
    if (!alreadyPresent) {
      const usesLeadingSlash = background.scripts.some((s) => typeof s === 'string' && s.trim().startsWith('/'))
      background.scripts = [
        usesLeadingSlash ? `/${COMPAT_RUNTIME_SCRIPT_NAME}` : COMPAT_RUNTIME_SCRIPT_NAME,
        ...background.scripts,
      ]
      changed = true
    }
  }

  return changed
}

const REWRITABLE_TEXT_EXTS = new Set(['.js', '.mjs', '.cjs', '.html', '.htm', '.css', '.json'])

async function listFilesRecursively(dir: string, prefix = ''): Promise<string[]> {
  const entries = await readdir(dir, { withFileTypes: true })
  const out: string[] = []
  for (const entry of entries) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      out.push(...(await listFilesRecursively(full, rel)))
    } else if (entry.isFile()) {
      out.push(rel)
    }
  }
  return out
}

function escapeRegExp(str: string): string {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/**
 * On iOS, `.appex` bundles are shallow (`App.appex/Info.plist`), and
 * `safari-web-extension-converter --ios-only` copies extension files straight
 * into the `.appex` root. If the Chrome extension contains a top-level
 * `resources/` directory (e.g. Vimium's `resources/tlds.txt`), case-insensitive
 * APFS makes `CFBundle` / `embeddedBinaryValidationUtility` mistake it for a
 * deep bundle's `Resources/` folder and fail `xcodebuild` with
 * "Couldn't load Info dictionary".
 *
 * Renaming top-level `resources/` → `__extport_ext_resources/` and updating
 * exact references to its files keeps the iOS bundle valid without breaking
 * extension code.
 */
async function relocateIosReservedResourcesDir(root: string): Promise<boolean> {
  const entries = await readdir(root, { withFileTypes: true })
  const match = entries.find((e) => e.isDirectory() && e.name.toLowerCase() === 'resources')
  if (!match) return false

  const oldDirName = match.name
  const oldFull = path.join(root, oldDirName)
  const newFull = path.join(root, IOS_RENAMED_RESOURCES_DIR)
  const innerFiles = await listFilesRecursively(oldFull)

  await rename(oldFull, newFull)

  if (innerFiles.length === 0) return true

  // Match exact references to actual files that lived inside `<oldDirName>/...`
  // (e.g. "resources/tlds.txt", "./resources/tlds.txt", "/resources/tlds.txt")
  // so unrelated URLs or identifiers containing "resources/" are never touched.
  const alt = innerFiles.map(escapeRegExp).join('|')
  const refRe = new RegExp(`(?<![A-Za-z0-9_-])${escapeRegExp(oldDirName)}\\/(${alt})(?![A-Za-z0-9_.-])`, 'g')

  const allFiles = await listFilesRecursively(root)
  for (const rel of allFiles) {
    if (!REWRITABLE_TEXT_EXTS.has(path.extname(rel).toLowerCase())) continue
    const full = path.join(root, ...rel.split('/'))
    const text = await readFile(full, 'utf-8').catch(() => undefined)
    if (text === undefined || !text.includes(`${oldDirName}/`)) continue
    const updated = text.replace(refRe, `${IOS_RENAMED_RESOURCES_DIR}/$1`)
    if (updated !== text) {
      await writeFile(full, updated, 'utf-8')
    }
  }

  return true
}

/**
 * Patches an unpacked extension directory for Safari compatibility:
 * 1. On iOS, relocates top-level `resources/` directories that collide with
 *    CFBundle's reserved `Resources/` directory name in shallow `.appex` bundles.
 * 2. Normalizes Safari-incompatible manifest fields (empty commands, incognito=split,
 *    use_dynamic_url, Chrome-only store metadata).
 * 3. Injects a lightweight Safari runtime API shim into background workers/scripts
 *    and extension HTML pages.
 * 4. Patches popup/options HTML files for Safari color-scheme and narrow-viewport layout.
 *
 * Returns the list of patched relative HTML paths.
 */
export async function patchExtensionForSafari(unpackedDir: string, platform: SafariPlatform): Promise<string[]> {
  const root = path.resolve(unpackedDir)
  if (platform === 'ios') {
    await relocateIosReservedResourcesDir(root)
  }
  const manifestPath = path.join(root, 'manifest.json')
  const raw = (await readFile(manifestPath, 'utf-8')).replace(/^\uFEFF/, '')
  const manifest = JSON.parse(raw) as Record<string, unknown>

  const manifestChanges = normalizeManifestForSafari(manifest)

  const cssPages = new Set(collectExtensionHtmlPages(manifest))
  const allHtmlPages = collectRuntimeHtmlPages(manifest)

  const targets: { relPosix: string; fullPath: string; applyCss: boolean }[] = []
  for (const page of allHtmlPages) {
    const fullPath = path.resolve(root, page)
    const rel = path.relative(root, fullPath)
    if (!rel || rel.startsWith('..') || path.isAbsolute(rel)) continue
    if (!(await isRegularFile(fullPath))) continue
    const relPosix = rel.split(path.sep).join('/')
    targets.push({ relPosix, fullPath, applyCss: cssPages.has(page) })
  }

  const hasBackground = Boolean(manifest.background && typeof manifest.background === 'object')
  const needsRuntimeShim = hasBackground || targets.length > 0
  if (needsRuntimeShim) {
    await writeFile(path.join(root, COMPAT_RUNTIME_SCRIPT_NAME), buildSafariRuntimeShim(), 'utf-8')
  }

  const bgWired = await wireBackgroundRuntimeShim(root, manifest)
  if (manifestChanges.length > 0 || bgWired) {
    await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf-8')
  }

  const hasCssTargets = targets.some((t) => t.applyCss)
  if (hasCssTargets) {
    await writeFile(path.join(root, COMPAT_STYLESHEET_NAME), buildSafariCompatCss(platform), 'utf-8')
  }

  const patched: string[] = []
  for (const target of targets) {
    const stylesheetHref = target.applyCss ? toRelativePosixHref(target.relPosix, COMPAT_STYLESHEET_NAME) : undefined
    const runtimeScriptHref = toRelativePosixHref(target.relPosix, COMPAT_RUNTIME_SCRIPT_NAME)
    const original = await readFile(target.fullPath, 'utf-8')
    const updated = patchHtmlDocument(original, stylesheetHref, runtimeScriptHref)
    if (updated !== original) {
      await writeFile(target.fullPath, updated, 'utf-8')
    }
    if (target.applyCss) {
      patched.push(target.relPosix)
    }
  }

  return patched
}
