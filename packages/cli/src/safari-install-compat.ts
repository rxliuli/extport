import { readFile, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { SafariPlatform } from './safari-build-args'

export const COMPAT_STYLESHEET_NAME = '__extport_safari_compat.css'

const VIEWPORT_META = '<meta name="viewport" content="width=device-width, initial-scale=1" />'
const COLOR_SCHEME_META = '<meta name="color-scheme" content="light dark" />'

const HAS_VIEWPORT_RE = /<meta\b[^>]*\bname\s*=\s*(?:"viewport"|'viewport'|viewport\b)[^>]*>/i
const HAS_COLOR_SCHEME_RE = /<meta\b[^>]*\bname\s*=\s*(?:"color-scheme"|'color-scheme'|color-scheme\b)[^>]*>/i
const HEAD_OPEN_RE = /<head\b[^>]*>/i
const HEAD_CLOSE_RE = /<\/head>/i
const HTML_OPEN_RE = /<html\b[^>]*>/i
const DOCTYPE_RE = /^\s*<!doctype\b[^>]*>/i

function normalizeManifestPagePath(value: unknown): string | undefined {
  if (typeof value !== 'string') return undefined
  const trimmed = value.trim()
  if (!trimmed || /^[a-z][a-z0-9+.-]*:/i.test(trimmed)) return undefined
  const withoutQuery = trimmed.split(/[?#]/, 1)[0] ?? ''
  const cleaned = withoutQuery.replace(/^(?:\.\/|\/)+/, '')
  return cleaned || undefined
}

/**
 * Extracts extension-owned HTML page paths (`action.default_popup`, `options_page`,
 * `options_ui.page`) from a parsed `manifest.json`, normalized and deduplicated.
 */
export function collectExtensionHtmlPages(manifest: Record<string, unknown>): string[] {
  const action =
    manifest.action && typeof manifest.action === 'object' ? (manifest.action as Record<string, unknown>) : undefined
  const browserAction =
    manifest.browser_action && typeof manifest.browser_action === 'object'
      ? (manifest.browser_action as Record<string, unknown>)
      : undefined
  const optionsUi =
    manifest.options_ui && typeof manifest.options_ui === 'object'
      ? (manifest.options_ui as Record<string, unknown>)
      : undefined

  const candidates = [action?.default_popup, browserAction?.default_popup, manifest.options_page, optionsUi?.page]
  const seen = new Set<string>()
  const pages: string[] = []

  for (const candidate of candidates) {
    const normalized = normalizeManifestPagePath(candidate)
    if (!normalized || seen.has(normalized)) continue
    seen.add(normalized)
    pages.push(normalized)
  }

  return pages
}

/**
 * Generates an external stylesheet (MV3 CSP-safe; no inline `<style>`) that:
 * 1. Declares `color-scheme: light dark` inside a cascade `@layer` so any
 *    unlayered `color-scheme` declared by the extension itself still wins.
 * 2. On iOS, prevents fixed-width desktop Chrome popups (e.g. `min-width: 400px`
 *    or `white-space: nowrap` headings) from overflowing narrow Safari sheets
 *    horizontally, without clipping content (`overflow-x: hidden`) or squishing
 *    custom controls.
 */
export function buildSafariCompatCss(platform: SafariPlatform): string {
  const shared = `/* Generated by extport for Safari Web Extension compatibility. */
@layer extport-compat {
  :root {
    color-scheme: light dark;
  }

  html,
  body {
    max-inline-size: 100%;
  }

  img,
  video {
    max-inline-size: 100%;
    block-size: auto;
  }

  svg {
    max-inline-size: 100%;
  }
}
`

  if (platform === 'macos') {
    return shared
  }

  return `${shared}
@media (max-width: 500px) {
  html,
  body {
    box-sizing: border-box;
    inline-size: 100% !important;
    min-inline-size: 0 !important;
    max-inline-size: 100% !important;
  }

  body > :is(div, main, section, article, form):first-of-type:last-of-type {
    box-sizing: border-box;
    inline-size: 100% !important;
    min-inline-size: 0 !important;
    max-inline-size: 100% !important;
  }

  body
    :is(
      div,
      main,
      section,
      article,
      form,
      header,
      footer,
      nav,
      aside,
      ul,
      ol,
      li,
      p,
      h1,
      h2,
      h3,
      h4,
      h5,
      h6,
      label,
      fieldset
    ) {
    min-inline-size: 0 !important;
    max-inline-size: 100% !important;
  }

  body :is(h1, h2, h3, h4, h5, h6, button) {
    white-space: normal !important;
    overflow-wrap: anywhere;
    text-wrap: balance;
  }
}
`
}

/**
 * Injects missing `<meta name="viewport">` and `<meta name="color-scheme" content="light dark">`
 * early in `<head>` (to avoid FOUC) and appends a `<link rel="stylesheet">` right before `</head>`.
 * Idempotent and preserves any explicit viewport or color-scheme already declared by the extension.
 */
export function patchHtmlDocument(html: string, stylesheetHref: string): string {
  const metasToInsert: string[] = []
  if (!HAS_VIEWPORT_RE.test(html)) metasToInsert.push(VIEWPORT_META)
  if (!HAS_COLOR_SCHEME_RE.test(html)) metasToInsert.push(COLOR_SCHEME_META)

  const linkTag = `<link rel="stylesheet" href="${stylesheetHref}" />`
  const hasStylesheet = html.includes(COMPAT_STYLESHEET_NAME)

  if (metasToInsert.length === 0 && hasStylesheet) {
    return html
  }

  const headOpenMatch = HEAD_OPEN_RE.exec(html)
  const headCloseMatch = HEAD_CLOSE_RE.exec(html)
  if (headOpenMatch && headCloseMatch && headCloseMatch.index > headOpenMatch.index) {
    let result = html
    if (metasToInsert.length > 0) {
      const insertPos = headOpenMatch.index + headOpenMatch[0].length
      const metaBlock = `\n    ${metasToInsert.join('\n    ')}`
      result = `${result.slice(0, insertPos)}${metaBlock}${result.slice(insertPos)}`
    }
    if (!hasStylesheet) {
      const updatedCloseMatch = HEAD_CLOSE_RE.exec(result)
      if (updatedCloseMatch) {
        result = `${result.slice(0, updatedCloseMatch.index)}    ${linkTag}\n  ${result.slice(updatedCloseMatch.index)}`
      }
    }
    return result
  }

  const headLines = [...metasToInsert, ...(hasStylesheet ? [] : [linkTag])]
  const headBlock = `<head>\n    ${headLines.join('\n    ')}\n  </head>`

  const htmlOpenMatch = HTML_OPEN_RE.exec(html)
  if (htmlOpenMatch) {
    const insertPos = htmlOpenMatch.index + htmlOpenMatch[0].length
    return `${html.slice(0, insertPos)}\n  ${headBlock}${html.slice(insertPos)}`
  }

  const doctypeMatch = DOCTYPE_RE.exec(html)
  if (doctypeMatch) {
    const insertPos = doctypeMatch.index + doctypeMatch[0].length
    return `${html.slice(0, insertPos)}\n${headBlock}\n${html.slice(insertPos)}`
  }

  return `${headBlock}\n${html}`
}

async function isRegularFile(filePath: string): Promise<boolean> {
  try {
    return (await stat(filePath)).isFile()
  } catch {
    return false
  }
}

/**
 * Patches extension popup/options HTML files in an unpacked extension directory
 * for Safari color-scheme and narrow-viewport compatibility.
 * Returns the list of patched relative HTML paths.
 */
export async function patchExtensionForSafari(unpackedDir: string, platform: SafariPlatform): Promise<string[]> {
  const root = path.resolve(unpackedDir)
  const manifestPath = path.join(root, 'manifest.json')
  const raw = await readFile(manifestPath, 'utf-8')
  const manifest = JSON.parse(raw) as Record<string, unknown>
  const pages = collectExtensionHtmlPages(manifest)

  const targets: { relPosix: string; fullPath: string }[] = []
  for (const page of pages) {
    const fullPath = path.resolve(root, page)
    const rel = path.relative(root, fullPath)
    if (!rel || rel.startsWith('..') || path.isAbsolute(rel)) continue
    if (!(await isRegularFile(fullPath))) continue
    targets.push({ relPosix: rel.split(path.sep).join('/'), fullPath })
  }

  if (targets.length === 0) return []

  const stylesheetPath = path.join(root, COMPAT_STYLESHEET_NAME)
  await writeFile(stylesheetPath, buildSafariCompatCss(platform), 'utf-8')

  const patched: string[] = []
  for (const target of targets) {
    const relHref = path.posix.relative(path.posix.dirname(target.relPosix), COMPAT_STYLESHEET_NAME)
    const stylesheetHref = relHref.startsWith('.') ? relHref : `./${relHref}`
    const original = await readFile(target.fullPath, 'utf-8')
    const updated = patchHtmlDocument(original, stylesheetHref)
    if (updated !== original) {
      await writeFile(target.fullPath, updated, 'utf-8')
    }
    patched.push(target.relPosix)
  }

  return patched
}
