import { readdir, readFile, rename, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { SafariPlatform } from './safari-build-args'

export const COMPAT_STYLESHEET_NAME = '__extport_safari_compat.css'
export const COMPAT_RUNTIME_SCRIPT_NAME = '__extport_safari_runtime.js'
export const COMPAT_BG_WRAPPER_NAME = '__extport_safari_bg.js'
export const IOS_RENAMED_RESOURCES_DIR = '__extport_ext_resources'

const VIEWPORT_META = '<meta name="viewport" content="width=device-width, initial-scale=1" />'
const COLOR_SCHEME_META = '<meta name="color-scheme" content="light dark" />'

const HAS_VIEWPORT_RE = /<meta\b[^>]*\bname\s*=\s*(?:"viewport"|'viewport'|viewport\b)[^>]*>/i
const HAS_COLOR_SCHEME_RE = /<meta\b[^>]*\bname\s*=\s*(?:"color-scheme"|'color-scheme'|color-scheme\b)[^>]*>/i
const HEAD_OPEN_RE = /<head\b[^>]*>/i
const HEAD_CLOSE_RE = /<\/head>/i
const HTML_OPEN_RE = /<html\b[^>]*>/i
const DOCTYPE_RE = /^\s*<!doctype\b[^>]*>/i

function normalizeManifestPagePath(value: unknown): string | undefined {
  if (typeof value !== 'string') return undefined
  const trimmed = value.trim()
  if (!trimmed || /^[a-z][a-z0-9+.-]*:/i.test(trimmed)) return undefined
  const withoutQuery = trimmed.split(/[?#]/, 1)[0] ?? ''
  const cleaned = withoutQuery.replace(/^(?:\.\/|\/)+/, '')
  return cleaned || undefined
}

/**
 * Extracts extension-owned HTML page paths (`action.default_popup`, `options_page`,
 * `options_ui.page`) from a parsed `manifest.json`, normalized and deduplicated.
 */
export function collectExtensionHtmlPages(manifest: Record<string, unknown>): string[] {
  const action =
    manifest.action && typeof manifest.action === 'object' ? (manifest.action as Record<string, unknown>) : undefined
  const browserAction =
    manifest.browser_action && typeof manifest.browser_action === 'object'
      ? (manifest.browser_action as Record<string, unknown>)
      : undefined
  const optionsUi =
    manifest.options_ui && typeof manifest.options_ui === 'object'
      ? (manifest.options_ui as Record<string, unknown>)
      : undefined

  const candidates = [action?.default_popup, browserAction?.default_popup, manifest.options_page, optionsUi?.page]
  const seen = new Set<string>()
  const pages: string[] = []

  for (const candidate of candidates) {
    const normalized = normalizeManifestPagePath(candidate)
    if (!normalized || seen.has(normalized)) continue
    seen.add(normalized)
    pages.push(normalized)
  }

  return pages
}

/**
 * Collects additional extension HTML pages (such as `devtools_page`) that benefit
 * from the Safari runtime JS shim even when we do not inject popup/options CSS.
 */
function collectRuntimeHtmlPages(manifest: Record<string, unknown>): string[] {
  const pages = collectExtensionHtmlPages(manifest)
  const seen = new Set(pages)
  const extra = [manifest.devtools_page]
  for (const candidate of extra) {
    const normalized = normalizeManifestPagePath(candidate)
    if (!normalized || seen.has(normalized)) continue
    seen.add(normalized)
    pages.push(normalized)
  }
  return pages
}

